// ── KERNFUNCTIES ──────────────────────────────────────────────

const I18n = {

    currentLang: "nl",
    pageLangs: ["nl", "en"],

    init() {
        // Detecteer welke talen op deze pagina beschikbaar zijn
        this.pageLangs = this._detectPageLangs();

        // Laad opgeslagen voorkeur of gebruik nl
        const saved = localStorage.getItem("ss_lang") || "nl";

        if (this.pageLangs.includes(saved)) {
            this.currentLang = saved;
        } else if (saved !== "nl" && saved !== "en") {
            // Gekozen taal niet beschikbaar op deze pagina
            this._showLangSwitchDialog(saved);
            this.currentLang = "nl";
        } else {
            this.currentLang = "nl";
        }

        this._apply();
        this._buildSwitcher();
    },

    setLang(lang) {
        if (!TRANSLATIONS[lang]) return;
        this.currentLang = lang;
        localStorage.setItem("ss_lang", lang);
        this._apply();
        this._buildSwitcher();
    },

    t(key) {
        const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS["nl"];
        return dict[key] || TRANSLATIONS["nl"][key] || key;
    },

    _apply() {
        document.querySelectorAll("[data-i18n]").forEach(el => {
            const key = el.getAttribute("data-i18n");
            const text = this.t(key);
            if (text) el.textContent = text;
        });
        document.documentElement.lang = this.currentLang;
    },

    _detectPageLangs() {
        // Kijk naar data-page-country attribuut of URL
        const meta = document.querySelector("meta[name='page-country']");
        if (meta) {
            const country = meta.content.toLowerCase();
            return COUNTRY_LANGS[country] || ["nl", "en"];
        }
        // Fallback: detecteer uit URL pad
        const path = window.location.pathname.toLowerCase();
        for (const [country, langs] of Object.entries(COUNTRY_LANGS)) {
            if (path.includes(country)) return langs;
        }
        return ["nl", "en"];
    },

    _buildSwitcher() {
        const container = document.getElementById("langSwitcher");
        if (!container) return;

        container.innerHTML = "";
        this.pageLangs.forEach(lang => {
            const btn = document.createElement("button");
            btn.className = "lang-btn" + (lang === this.currentLang ? " active" : "");
            btn.textContent = lang.toUpperCase();
            btn.setAttribute("data-lang", lang);
            btn.addEventListener("click", () => this.setLang(lang));
            container.appendChild(btn);
        });
    },

    _showLangSwitchDialog(unavailableLang) {
        // Toon pop-up als gekozen taal niet beschikbaar is
        const dialog = document.createElement("div");
        dialog.style.cssText = `
            position:fixed; inset:0; background:rgba(0,0,0,0.8);
            z-index:9999; display:flex; align-items:center; justify-content:center;
        `;

        const langName = LANG_NAMES[unavailableLang] || unavailableLang;
        const avail = this.pageLangs
            .map(l => `<button onclick="I18n.setLang('${l}'); this.closest('.ss-dialog').remove();"
                        style="padding:10px 20px; margin:4px; background:#c8892a; color:#000;
                               border:none; border-radius:4px; font-weight:700; cursor:pointer;">
                          ${LANG_NAMES[l] || l}
                       </button>`)
            .join("");

        dialog.innerHTML = `
            <div class="ss-dialog" style="
                background:#1c1c1c; border:1px solid #2e2e2e; border-radius:8px;
                padding:32px; max-width:400px; text-align:center;
            ">
                <p style="color:#c8892a; font-size:12px; letter-spacing:0.2em; margin-bottom:12px;">
                    🌍 TAAL NIET BESCHIKBAAR
                </p>
                <p style="color:#e8e4dc; margin-bottom:8px;">
                    <strong>${langName}</strong> is niet beschikbaar op deze pagina.
                </p>
                <p style="color:#888; font-size:14px; margin-bottom:24px;">
                    Kies een beschikbare taal:
                </p>
                <div>${avail}</div>
            </div>
        `;

        dialog.addEventListener("click", e => {
            if (e.target === dialog) dialog.remove();
        });

        document.body.appendChild(dialog);
    }
};

// Start zodra DOM klaar is
document.addEventListener("DOMContentLoaded", () => I18n.init());
